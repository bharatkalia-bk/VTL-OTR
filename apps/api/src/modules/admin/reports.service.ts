import { Inject, Injectable, NotFoundException, type OnModuleInit } from '@nestjs/common';
import ExcelJS from 'exceljs';
import { z } from 'zod';
import { AppError } from '../../common/errors';
import { parseOrThrow } from '../../common/zod';
import { AuditService } from '../../infra/audit.service';
import { PrismaService } from '../../infra/prisma.service';
import { QueueService } from '../../infra/queue.service';
import { STORAGE, type StorageAdapter } from '../../infra/storage';
import { FieldCrypto } from '../../security/field-crypto';

export const REPORT_TYPES = ['APPLICANTS', 'CATEGORY_COUNTS', 'PAYMENTS', 'REGISTRATIONS_BY_STATE', 'ADMIT_CARDS'] as const;
const createSchema = z.object({ type: z.enum(REPORT_TYPES), format: z.enum(['xlsx', 'csv']).default('xlsx'), examId: z.string().uuid().optional(), from: z.string().optional(), to: z.string().optional() });
type Row = Record<string, string | number | null>;

/** Exports are generated by the worker and downloaded via short-lived signed URLs. */
@Injectable()
export class ReportsService implements OnModuleInit {
  constructor(
    private readonly prisma: PrismaService,
    private readonly queue: QueueService,
    private readonly audit: AuditService,
    private readonly crypto: FieldCrypto,
    @Inject(STORAGE) private readonly storage: StorageAdapter,
  ) {}

  onModuleInit(): void {
    this.queue.register('reports', 'generate', async (d) => this.run(String(d.jobId)));
  }

  async create(adminId: string, body: unknown) {
    const b = parseOrThrow(createSchema, body);
    if (['APPLICANTS', 'PAYMENTS', 'ADMIT_CARDS', 'CATEGORY_COUNTS'].includes(b.type) && !b.examId && b.type !== 'PAYMENTS' && b.type !== 'CATEGORY_COUNTS') throw new AppError('EXAM_REQUIRED', 'Select an exam.');
    const job = await this.prisma.reportJob.create({ data: { type: b.type, format: b.format, params: b, createdById: adminId } });
    await this.audit.log({ action: 'REPORT_REQUESTED', entity: 'ReportJob', entityId: job.id, actorType: 'ADMIN', actorId: adminId, after: b });
    await this.queue.add('reports', 'generate', { jobId: job.id });
    return this.prisma.reportJob.findUniqueOrThrow({ where: { id: job.id } });
  }

  list(adminId: string) {
    return this.prisma.reportJob.findMany({ where: { createdById: adminId }, orderBy: { createdAt: 'desc' }, take: 50 });
  }

  async download(adminId: string, id: string) {
    const j = await this.prisma.reportJob.findFirst({ where: { id } });
    if (!j || !j.objectKey) throw new NotFoundException({ code: 'NOT_READY', message: 'Report not ready.' });
    await this.audit.log({ action: 'REPORT_DOWNLOADED', entity: 'ReportJob', entityId: id, actorType: 'ADMIN', actorId: adminId });
    return { url: await this.storage.signedUrl(j.objectKey, 300, `${j.type.toLowerCase()}-${j.createdAt.toISOString().slice(0, 10)}.${j.format}`) };
  }

  private async rows(type: (typeof REPORT_TYPES)[number], p: z.infer<typeof createSchema>): Promise<Row[]> {
    switch (type) {
      case 'APPLICANTS': {
        const apps = await this.prisma.application.findMany({ where: { examId: p.examId, status: { not: 'DRAFT' } }, include: { candidate: { include: { profile: true } }, exam: { include: { posts: true } } }, orderBy: { applicationNo: 'asc' } });
        return apps.map((a) => ({
          'Application No': a.applicationNo, 'OTR ID': a.candidate.otrId, Name: this.crypto.decOpt(a.candidate.profile?.fullNameEnc), "Father's Name": this.crypto.decOpt(a.candidate.profile?.fatherNameEnc),
          DOB: this.crypto.decOpt(a.candidate.profile?.dobEnc), Gender: a.candidate.profile?.gender ?? null, Category: a.candidate.profile?.category ?? null, PwD: a.candidate.profile?.pwd ? 'Y' : 'N',
          State: a.candidate.profile?.stateCode ?? null, Posts: a.postIds.map((id) => a.exam.posts.find((x) => x.id === id)?.code).join(', '), Fee: a.feeAmount, Status: a.status, Submitted: a.submittedAt?.toISOString() ?? null,
        }));
      }
      case 'CATEGORY_COUNTS': {
        const where = { status: { not: 'DRAFT' as const }, ...(p.examId && { examId: p.examId }) };
        const apps = await this.prisma.application.findMany({ where, select: { status: true, candidate: { select: { profile: { select: { category: true, gender: true, pwd: true } } } } } });
        const m = new Map<string, Row>();
        for (const a of apps) {
          const k = `${a.candidate.profile?.category}|${a.candidate.profile?.gender}`;
          const r = m.get(k) ?? { Category: a.candidate.profile?.category ?? '-', Gender: a.candidate.profile?.gender ?? '-', Total: 0, PwD: 0, Paid: 0 };
          r.Total = Number(r.Total) + 1;
          if (a.candidate.profile?.pwd) r.PwD = Number(r.PwD) + 1;
          if (a.status === 'PAID' || a.status === 'FEE_EXEMPT') r.Paid = Number(r.Paid) + 1;
          m.set(k, r);
        }
        return [...m.values()];
      }
      case 'PAYMENTS': {
        const pays = await this.prisma.payment.findMany({ where: { ...(p.examId && { application: { examId: p.examId } }), ...(p.from && { createdAt: { gte: new Date(p.from), ...(p.to && { lte: new Date(p.to) }) } }) }, include: { application: { select: { applicationNo: true, exam: { select: { code: true } } } } }, orderBy: { createdAt: 'asc' } });
        return pays.map((x) => ({ 'Merchant Txn': x.merchantTxnId, 'Gateway Txn': x.gatewayTxnId, Exam: x.application.exam.code, 'Application No': x.application.applicationNo, Amount: x.amount, Status: x.status, Reconciled: x.reconciledAt?.toISOString() ?? null, Note: x.reconciliationNote, Created: x.createdAt.toISOString() }));
      }
      case 'REGISTRATIONS_BY_STATE': {
        const g = await this.prisma.candidateProfile.groupBy({ by: ['stateCode'], _count: true });
        const states = new Map((await this.prisma.state.findMany()).map((s) => [s.code, s.nameEn]));
        return g.map((r) => ({ State: states.get(r.stateCode ?? '') ?? 'Not provided', Registrations: r._count })).sort((a, b) => Number(b.Registrations) - Number(a.Registrations));
      }
      case 'ADMIT_CARDS': {
        const acs = await this.prisma.admitCard.findMany({ where: { examId: p.examId }, include: { centre: { include: { city: true } }, application: { select: { applicationNo: true, candidate: { select: { otrId: true } } } } }, orderBy: { rollNo: 'asc' } });
        return acs.map((a) => ({ 'Roll No': a.rollNo, 'Application No': a.application.applicationNo, 'OTR ID': a.application.candidate.otrId, Centre: a.centre?.name ?? 'UNALLOCATED', City: a.centre?.city.cityName ?? null, Method: a.allocationMethod, Released: a.releasedAt?.toISOString() ?? null, Downloaded: a.downloadedAt?.toISOString() ?? null }));
      }
    }
  }

  async run(jobId: string) {
    const j = await this.prisma.reportJob.update({ where: { id: jobId }, data: { status: 'RUNNING' } });
    try {
      const p = createSchema.parse(j.params);
      const rows = await this.rows(p.type, p);
      const headers = rows[0] ? Object.keys(rows[0]) : ['No data'];
      let buf: Buffer;
      if (j.format === 'csv') {
        const esc = (v: unknown) => { const s = v === null || v === undefined ? '' : String(v); return /[",\n]/.test(s) || /^[=+\-@]/.test(s) ? `"${s.replace(/^([=+\-@])/, "'$1").replace(/"/g, '""')}"` : s; };
        buf = Buffer.from(`\uFEFF${[headers.join(','), ...rows.map((r) => headers.map((h) => esc(r[h])).join(','))].join('\n')}`, 'utf8');
      } else {
        const wb = new ExcelJS.Workbook();
        wb.creator = 'VTL OTR';
        const ws = wb.addWorksheet(p.type);
        ws.columns = headers.map((h) => ({ header: h, key: h, width: Math.min(40, Math.max(12, h.length + 4)) }));
        ws.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
        ws.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF07102D' } };
        rows.forEach((r) => ws.addRow(r));
        ws.views = [{ state: 'frozen', ySplit: 1 }];
        buf = Buffer.from(await wb.xlsx.writeBuffer());
      }
      const key = `reports/${jobId}.${j.format}`;
      await this.storage.put(key, buf, j.format === 'csv' ? 'text/csv' : 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
      return this.prisma.reportJob.update({ where: { id: jobId }, data: { status: 'DONE', objectKey: key, rowCount: rows.length, completedAt: new Date() } });
    } catch (e) {
      await this.prisma.reportJob.update({ where: { id: jobId }, data: { status: 'FAILED', error: String(e).slice(0, 500) } });
      throw e;
    }
  }
}
